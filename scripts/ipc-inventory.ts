#!/usr/bin/env bun
/** Maintain the literal compatibility fixture; CI never rewrites it. */
import assert from 'node:assert/strict'
import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { RPC_CHANNELS } from '../packages/shared/src/protocol/channels'

const root = resolve(import.meta.dir, '..')
const file = resolve(root, 'apps/electron/src/shared/__tests__/ipc-channels.test.ts')
function flatten(value: Record<string, unknown>): string[] {
  return Object.values(value).flatMap(item => typeof item === 'string' ? [item]
    : item && typeof item === 'object' ? flatten(item as Record<string, unknown>) : [])
}
const actual = flatten(RPC_CHANNELS).sort()
assert.equal(new Set(actual).size, actual.length, 'Duplicate RPC wire strings')
const source = readFileSync(file, 'utf8')
const block = /\/\/ Auto-generated by scripts\/ipc-inventory\.ts[^\n]*\nconst EXPECTED_CHANNELS: string\[\] = (\[[\s\S]*?\])\nconst EXPECTED_COUNT = EXPECTED_CHANNELS\.length\n\/\/ End auto-generated/
const existing = source.match(block)
assert(existing, 'Missing literal IPC fixture markers')
const expected = JSON.parse(existing[1]!) as string[]
const added = actual.filter(channel => !expected.includes(channel)), removed = expected.filter(channel => !actual.includes(channel))
if (process.argv.slice(2).includes('--update')) {
  const replacement = '// Auto-generated by scripts/ipc-inventory.ts — DO NOT edit by hand.\n' +
    `const EXPECTED_CHANNELS: string[] = ${JSON.stringify(actual, null, 2)}\nconst EXPECTED_COUNT = EXPECTED_CHANNELS.length\n// End auto-generated`
  writeFileSync(file, source.replace(block, replacement))
  console.log(JSON.stringify({ count: actual.length, added, removed, updated: true }))
} else {
  assert.deepEqual(expected, actual, `RPC fixture drift: added ${added.join(', ')}; removed ${removed.join(', ')}. Review wire compatibility, then run scripts/ipc-inventory.ts --update.`)
  console.log(`IPC compatibility fixture OK: ${actual.length} literal channels`)
}
