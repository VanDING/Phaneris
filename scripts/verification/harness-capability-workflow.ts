/** Scenarios declared before implementation. Contract integration, not live model quality. */
import assert from 'node:assert/strict'
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { verificationWorkflow } from './verification-artifacts'

await verificationWorkflow('harness-capability', async evidence => {
  const { prepareToolResultView } = await import('../../packages/pi-agent-server/src/tool-result-view')
  const { getToolDefsAsJsonSchema } = await import('../../packages/session-tools-core/src/tool-defs')
  const { createPhanerisToolSearch } = await import('../../packages/pi-agent-server/src/tool-discovery')
  const { PrerequisiteManager } = await import('../../packages/shared/src/agent/core/prerequisite-manager')
  const { buildAssistantPromptModules } = await import('../../packages/shared/src/prompts/assistant-prompt')
  const { DOC_REFS } = await import('../../packages/shared/src/docs')
  const { PERMISSION_MODE_CONFIG } = await import('../../packages/shared/src/agent/mode-types')
  const { canonicalContextToPiMessages } = await import('../../packages/pi-agent-server/src/canonical-model-context')
  const workspace = join(evidence.directory, 'workspace')
  mkdirSync(workspace, { recursive: true })
  const checks: string[] = []
  const text = 'FIRST_EVIDENCE\n' + 'source evidence '.repeat(20000) + '\nLAST_COUNTEREVIDENCE'
  const image = { type: 'image' as const, data: 'aGVsbG8=', mimeType: 'image/png' }
  const original = { content: [{ type: 'text' as const, text }, image], structuredContent: { rows: [1, 2, 3] }, details: { marker: 'retain' } }
  const view = await prepareToolResultView({ result: original, toolName: 'mcp__fixture__query', input: {}, sessionPath: workspace, budgetChars: 4000 })
  assert.deepEqual(view.content.filter(c => c.type !== 'text'), [image])
  assert.deepEqual(view.structuredContent, original.structuredContent)
  const receipt = view.details.phanerisResult
  assert.equal(receipt.modelView.kind, 'preview')
  assert.equal(receipt.coverage.kind, 'unknown')
  assert.equal(readFileSync(receipt.recovery.path!, 'utf8'), text)
  assert.match(view.content.filter(c => c.type === 'text').map(c => c.text).join(''), /LAST_COUNTEREVIDENCE/)
  assert.equal(view.details.marker, 'retain')
  checks.push('HC02 mixed content, exact spill, head/tail and canonical program value')
  const nonVision = await prepareToolResultView({ result: original, toolName: 'query', input: {}, sessionPath: workspace, budgetChars: 4000, supportsImages: false })
  assert(nonVision.content.some(block => block.type === 'image'))
  assert.match(JSON.stringify(nonVision.content), /cannot consume these image blocks/)
  checks.push('HC04 unsupported image input is explicit without deleting canonical media')
  const replay = canonicalContextToPiMessages({ cursor: 1, items: [{ kind: 'tool_result', seq: 1, operationId: 'op', toolCallId: 'call', toolName: 'query', result: view, isError: false }] } as never, {} as never)
  assert.deepEqual((replay[0] as any).content, view.content)
  checks.push('HC11 canonical replay preserves ordered model blocks')
  const native = { content: [{ type: 'text' as const, text: '[Showing lines 1-20 of 100. Use offset=21 to continue.]' }], details: { truncation: { truncated: true } } }
  const read = await prepareToolResultView({ result: native, toolName: 'Read', input: { path: 'reference.md' }, sessionPath: workspace, budgetChars: 10 })
  assert.deepEqual(read.content, native.content)
  assert.equal(read.details.phanerisResult.coverage.kind, 'partial')
  checks.push('HC01 native bounded read is not transformed again')
  const blocked = join(workspace, 'not-a-directory')
  writeFileSync(blocked, 'file')
  const failure = await prepareToolResultView({ result: original, toolName: 'query', input: {}, sessionPath: blocked, budgetChars: 4000 })
  assert.equal(failure.details.phanerisResult.recovery.status, 'unavailable')
  assert(!failure.content.some(c => c.type === 'text' && c.text.includes('saved to:')))
  checks.push('HC03 spill failure is truthful and preserves media')
  const manager = new PrerequisiteManager({ workspaceRootPath: workspace })
  const path = join(workspace, 'SKILL.md')
  writeFileSync(path, 'instruction')
  manager.registerSkillPrerequisites([path])
  manager.trackReadTool({ path }, '[Large response summarized]\nsummary')
  assert.equal(manager.hasRead(path), false)
  manager.trackReadTool({ path }, '[Relevant excerpt: 3 of 20 chunks]\nexcerpt')
  assert.equal(manager.hasRead(path), false)
  manager.trackSuccessfulBashRead(`echo ${path}`)
  assert.equal(manager.hasRead(path), false)
  checks.push('HC04 derived text and arbitrary shell do not prove full reading')
  const { createReadToolDefinition, detectSupportedImageMimeTypeFromFile } = await import('@earendil-works/pi-coding-agent')
  const { readCapture, readFileWithEvidence } = await import('../../packages/pi-agent-server/src/tool-result-view')
  const { access } = await import('node:fs/promises')
  writeFileSync(path, 'first\nsecond\nthird')
  const nativeRead = createReadToolDefinition(workspace, { operations: { access, readFile: readFileWithEvidence, detectImageMimeType: detectSupportedImageMimeTypeFromFile } })
  const deliver = async (file: string, offset: number, limit: number) => {
    const capture = {}
    const input = { path: file, offset, limit }
    const result = await readCapture.run(capture, () => nativeRead.execute('read-range', input, undefined, undefined, {} as never))
    const bounded = await prepareToolResultView({ result, toolName: 'Read', input, sessionPath: workspace, budgetChars: 4000, capture })
    manager.trackReadTool(input, bounded.content.filter(c => c.type === 'text').map(c => c.text).join(''), bounded.details.phanerisResult)
    return bounded.details.phanerisResult
  }
  const first = await deliver(path, 1, 1)
  assert.equal(manager.hasRead(path), false)
  await deliver(first.recovery.path!, 2, 2)
  assert.equal(manager.hasRead(path), true)
  writeFileSync(path, 'CHANGED')
  assert.equal(manager.hasRead(path), false)
  assert.equal(readFileSync(first.recovery.path!, 'utf8'), 'first\nsecond\nthird')
  manager.resetReadState()
  assert.equal(manager.hasRead(path), false)
  assert.equal(manager.checkPrerequisites('Write').allowed, false)
  checks.push('HC05 HC12 real Pi range coverage, immutable snapshot, mutation and compaction invalidation')
  const literal = join(workspace, 'literal-marker.md')
  writeFileSync(literal, 'Instructions may discuss [Tool return preview] as literal source text.')
  await deliver(literal, 1, 1)
  assert.equal(manager.hasRead(literal), true, 'Typed exact source coverage must take precedence over historical text heuristics')
  checks.push('HC04 exact source containing a preview marker remains original evidence')
  const defs = getToolDefsAsJsonSchema({ prefix: 'mcp__session__' })
  assert.equal(defs.find(t => t.name.endsWith('__list_pages'))?.exposure, 'deferred')
  assert.equal(defs.find(t => t.name.endsWith('__ask_user'))?.exposure, 'direct')
  let active = ['read']
  const catalog = defs.map(d => ({ ...d, parameters: d.inputSchema }))
  const search = createPhanerisToolSearch({ getAllTools: () => catalog, getActiveTools: () => active, setActiveTools: (names: string[]) => { active = names } } as never, name => defs.find(t => t.name === name)?.availability)
  const directory = await search.execute('dir', { query: '', limit: 2, offset: 2 }, undefined, undefined, {} as never)
  assert.deepEqual(active, ['read'])
  assert.match(JSON.stringify(directory), /hasMore/)
  const found = await search.execute('pages', { query: '页面' }, undefined, undefined, {} as never)
  assert.match(JSON.stringify(found), /list_pages/)
  assert(active.some(t => t.endsWith('__list_pages')))
  assert.match(JSON.stringify(await search.execute('again', { query: 'list_pages' }, undefined, undefined, {} as never)), /already_available/)
  checks.push('HC06 internal family aliases, directory paging and stable activation')
  if (process.platform === 'win32') {
    const unavailable = await search.execute('unsupported', { query: 'script_sandbox' }, undefined, undefined, {} as never)
    assert.match(JSON.stringify(unavailable), /unsupported/)
    assert(!active.some(name => name.endsWith('__script_sandbox')))
    checks.push('HC08 unsupported isolation is discoverable but never activated')
  }
  const facts = { workspacePath: workspace, backendName: 'Pi', platform: 'win32', browserTools: false, managedConfiguration: false, developerFeedback: false, decideTool: false, docs: DOC_REFS, permissionModes: PERMISSION_MODE_CONFIG }
  const resident = buildAssistantPromptModules(facts)
  assert(!resident.some(s => s.id === 'pages' || s.id === 'session-management'))
  assert(resident.some(s => s.id === 'permissions'))
  assert(!resident.map(s => s.content).join('').includes('Skills available:'))
  checks.push('HC13 resident permissions and explicit skills with deferred workflows')
  evidence.json('harness-capability.json', { checks, receipt, directory: directory.details, fixture: workspace, scope: 'Contract integration; real filesystem, real definitions and SDK adapters; no live provider' })
  evidence.complete(checks, ['live model quality', 'native cross-platform isolation', 'signed packaging'])
  console.log(JSON.stringify({ passed: checks.length, output: evidence.directory }))
})
