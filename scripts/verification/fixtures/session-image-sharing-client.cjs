const assert = require('node:assert/strict')
const { readFileSync, writeFileSync, readdirSync, existsSync } = require('node:fs')
const { join } = require('node:path')
const { _electron } = require('playwright')
const { firstBusinessWindow } = require('./electron-windows.cjs')
;(async () => {
  const fixture = JSON.parse(readFileSync(process.argv[2], 'utf8'))
  const env = { ...process.env, PHANERIS_CONFIG_DIR: fixture.config, PHANERIS_RPC_PORT: '0',
    PHANERIS_DISABLE_MESSAGING: '1', PHANERIS_TELEMETRY_ENABLED: '0', NODE_ENV: 'production' }
  delete env.ELECTRON_RUN_AS_NODE; delete env.VITE_DEV_SERVER_URL; delete env.NODE_OPTIONS
  const app = await _electron.launch({ args: [join(fixture.root, 'apps/electron')], cwd: fixture.root, env, timeout: 30000 })
  const checks = [], errors = []
  let page
  try {
    page = await firstBusinessWindow(app)
    page.setDefaultTimeout(20000); page.on('pageerror', error => errors.push(error.message))
    await page.context().tracing.start({ screenshots: true, snapshots: true })
    await page.evaluate(id => window.dispatchEvent(new CustomEvent('phaneris-navigate', { detail: { route: 'allSessions/session/' + id }, bubbles: true })), fixture.session)
    await page.getByText('NATIVE-SHARE-END', { exact: false }).waitFor()
    const language = await page.evaluate(() => localStorage.getItem('i18nextLng'))
    const zh = !language || language.startsWith('zh')
    const words = zh ? { more: '更多选项', share: '分享为图片', rename: '重命名', input: '重命名会话', back: '返回修改', cancel: '取消', preview: '图片预览', save: '保存图片' }
      : { more: 'More options', share: 'Share as image', rename: 'Rename', input: 'Rename Session', back: 'Back to selection', cancel: 'Cancel', preview: 'Image preview', save: 'Save image' }
    assert.equal(await page.evaluate(() => window.electronAPI.getRuntimeEnvironment()), 'electron')
    assert.equal(await page.evaluate(() => typeof window.electronAPI.shareImages.save), 'function')
    checks.push('production preload exposes native-only capability')
    await page.getByRole('button', { name: words.more, exact: true }).click()
    await page.getByRole('menuitem', { name: words.rename, exact: true }).click()
    const input = page.getByRole('textbox', { name: words.input, exact: true })
    await input.waitFor(); assert.equal(await input.evaluate(element => element === document.activeElement), true)
    await input.fill('Native renamed title'); await input.press('Enter')
    await page.getByRole('button', { name: 'Native renamed title', exact: true }).waitFor()
    const sessionFile = join(fixture.workspace, 'sessions', fixture.session, 'session.jsonl')
    const deadline = Date.now() + 5000
    while (JSON.parse(readFileSync(sessionFile, 'utf8').split('\n')[0]).name !== 'Native renamed title' && Date.now() < deadline) await new Promise(resolve => setTimeout(resolve, 50))
    assert.equal(JSON.parse(readFileSync(sessionFile, 'utf8').split('\n')[0]).name, 'Native renamed title', 'Inline rename must persist before metadata watcher reads it')
    checks.push('original More menu opens focused inline rename and persists')
    const editor = page.locator('[contenteditable="true"]').first()
    const closeLabel = zh ? '关闭' : 'Close'
    assert.equal(await page.locator('[data-panel-role="content"]').getByRole('button', { name: closeLabel, exact: true }).count(), 1)
    await editor.fill('保留的客户端草稿')
    await page.getByRole('button', { name: words.share, exact: true }).last().click()
    assert.equal(await page.getByRole('heading', { name: 'Native renamed title', exact: true }).isVisible(), true)
    await page.locator('[data-share-select-id="a1"] input').waitFor()
    assert.equal(await page.locator('input[type=checkbox]:checked').count(), 1)
    assert.equal(await page.locator('[data-share-select-id="a1"] input').isChecked(), true)
    const exports = join(fixture.workspace, 'sessions', fixture.session, 'exports')
    assert.equal(existsSync(exports), false)
    checks.push('answer entry preselects answer; preview creates no exports')
    await page.screenshot({ path: join(fixture.output, 'native-selection.png') })
    await page.getByRole('button', { name: words.preview, exact: true }).click()
    await page.locator('[data-share-preview-index]').first().waitFor()
    assert.equal(await page.locator('[data-share-preview-index] .share-title').innerText(), 'Native renamed title')
    await page.screenshot({ path: join(fixture.output, 'native-preview.png') })
    await page.getByRole('button', { name: words.save, exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('[role="alert"]') && [...document.querySelectorAll('button')].some(button => /打开位置|Show file/.test(button.textContent)))
    const batches = readdirSync(join(exports, 'shares'))
    assert.equal(batches.length, 1)
    const png = join(exports, 'shares', batches[0], '01.png')
    const bytes = readFileSync(png); assert.equal(bytes.readUInt32BE(16), 1440)
    writeFileSync(join(fixture.output, 'native-share.png'), bytes)
    checks.push('bundled file fonts render and explicit Save retains 1440px PNG')
    await page.getByRole('button', { name: words.back, exact: true }).last().click()
    await page.getByRole('button', { name: words.cancel, exact: true }).click()
    assert.equal(await editor.textContent(), '保留的客户端草稿')
    await page.waitForFunction(label => [...document.querySelectorAll('button[aria-label]')].filter(button => button.getAttribute('aria-label') === label).at(-1) === document.activeElement, words.share)
    await page.getByRole('button', { name: words.share, exact: true }).first().click()
    await page.locator('[data-share-select-id="a1"] input').waitFor()
    assert.equal(await page.locator('input[type=checkbox]:checked').count(), 0)
    assert(await page.locator('[data-share-select-id]').count() < fixture.eligibleCount, 'History is not all mounted')
    await page.getByRole('button', { name: zh ? '全选' : 'Select all', exact: true }).click()
    assert((await page.locator('.share-selection-bar').innerText()).includes(String(fixture.eligibleCount)))
    await page.getByRole('button', { name: words.preview, exact: true }).click()
    await page.locator('.share-spread').waitFor()
    assert((await page.locator('.share-spread').innerText()).includes('HISTORY-FIRST'))
    assert((await page.locator('.share-spread').innerText()).includes('NATIVE-SHARE-END'))
    assert(await page.locator('.share-spread .share-page').count() > 1)
    await page.screenshot({ path: join(fixture.output, 'native-history-joined.png') })
    await page.getByRole('button', { name: words.back, exact: true }).click()
    await page.getByRole('button', { name: words.cancel, exact: true }).click()
    checks.push('header starts empty; draft and entry focus survive share exit')
    await page.locator('[data-panel-role="content"]').getByRole('button', { name: closeLabel, exact: true }).click()
    await page.getByText('NATIVE-SHARE-END', { exact: false }).waitFor({ state: 'detached' })
    assert(existsSync(sessionFile), 'Closing the view must retain its session')
    await page.evaluate(id => window.dispatchEvent(new CustomEvent('phaneris-navigate', { detail: { route: 'allSessions/session/' + id }, bubbles: true })), fixture.session)
    await page.getByText('NATIVE-SHARE-END', { exact: false }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Native renamed title', exact: true }).count(), 1)
    assert.equal(await editor.textContent(), '保留的客户端草稿')
    checks.push('single-conversation close retains session and reopening restores title and draft')
    assert.deepEqual(errors, [])
  } finally {
    writeFileSync(join(fixture.output, 'client-results.json'), JSON.stringify({ checks, errors }, null, 2))
    if (page) { await page.screenshot({ path: join(fixture.output, 'native-final.png') }); await page.context().tracing.stop({ path: join(fixture.output, 'trace.zip') }) }
    await app.close()
  }
})().catch(error => { console.error(error); process.exitCode = 1 })
