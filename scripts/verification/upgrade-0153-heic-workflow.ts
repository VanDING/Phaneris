#!/usr/bin/env bun
/**
 * HEIC/HEIF decoder acceptance: detection, container parsing, and the bounded
 * worker that performs the transcode.
 *
 * Complements `upgrade-0153-heic-store-workflow.ts` (the production RPC path) by
 * covering properties only observable at this layer:
 *
 *   - the dimension reader resolves the *primary image's* `ispe` through
 *     `pitm`/`ipma`/`ipco` instead of scanning for the literal bytes, so a decoy
 *     `ispe` inside a `free` box cannot spoof it, and a container without usable
 *     dimensions is refused rather than decoded unbounded;
 *   - the deadline terminates the worker (the synchronous libheif decode and
 *     jpeg-js encode cannot be interrupted from the calling thread);
 *   - the event loop keeps ticking while a transcode runs;
 *   - concurrent transcodes stay under the configured limit.
 *
 * Fixtures are regenerated by `scripts/verification/upgrade-0153-fixtures.ts`.
 *
 * Usage: bun run scripts/verification/upgrade-0153-heic-workflow.ts
 */
import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { VerificationRun } from './verification-artifacts'
import {
  HEIC_DECODE_TIMEOUT_MS, HEIC_MAX_CONCURRENT_TRANSCODES, MAX_HEIC_BYTES, MAX_HEIC_PIXELS,
  decodeHeicToJpeg, ensureDecodableImage, heicTranscodeStats, isAvifBuffer, isHeicBuffer,
  isHeicExtension, isHeicMime, needsHeicTranscode, readHeicDimensions, resolveHeicDecoderModule,
} from '../../packages/server-core/src/services/heic'

const root = resolve(import.meta.dir, '../..')
const evidence = new VerificationRun('upgrade-0153-heic')
const sha256 = (value: Buffer | string) => createHash('sha256').update(value).digest('hex')
const scenes: string[] = []
let failure: unknown

try {
  evidence.checkArguments()
  const fixtures = join(root, '.cache/upgrade-20261018/fixtures')
  if (!existsSync(join(fixtures, 'manifest.json'))) {
    throw new Error('Missing fixtures; run: bun run scripts/verification/upgrade-0153-fixtures.ts')
  }
  const manifest = JSON.parse(readFileSync(join(fixtures, 'manifest.json'), 'utf8')) as {
    samples: Record<string, { bytes: number; sha256: string; width: number; height: number }>
    encoders: Record<string, string>
  }
  const read = (name: string) => readFileSync(join(fixtures, name))
  for (const name of Object.keys(manifest.samples)) {
    assert.equal(sha256(read(name)), manifest.samples[name]!.sha256, `fixture ${name} must match its manifest hash`)
  }
  const heic = read('photo.heic')
  const avif = read('photo.avif')
  const jpeg = read('control.jpg')
  const report: Record<string, unknown> = {
    fixtures: { encoder: manifest.encoders, heic: manifest.samples['photo.heic'] },
    decoder: {
      module: resolveHeicDecoderModule(), maxBytes: MAX_HEIC_BYTES, maxPixels: MAX_HEIC_PIXELS,
      timeoutMs: HEIC_DECODE_TIMEOUT_MS, maxConcurrent: HEIC_MAX_CONCURRENT_TRANSCODES,
    },
  }

  // --- HE-01: AVIF is never treated as HEIC --------------------------------
  assert.equal(isAvifBuffer(avif), true, 'a real AVIF must be recognised as AVIF')
  assert.equal(isHeicBuffer(avif), false, 'a real AVIF must NOT be detected as HEIC')
  assert.equal(needsHeicTranscode(avif, 'image/avif'), false)
  assert.equal(needsHeicTranscode(avif, 'image/heic'), false, 'a wrong MIME must not force an AVIF transcode')
  const avifBrands = avif.toString('latin1', 8, Math.min(avif.length, 64))
  assert(avifBrands.includes('avif') && avifBrands.includes('mif1'), 'the AVIF fixture must carry both brands')
  assert.equal(isHeicBuffer(heic), true)
  assert.equal(isHeicBuffer(jpeg), false)
  assert.equal(isHeicExtension('photo.HEIC'), true)
  assert.equal(isHeicExtension('photo.jpg'), false)
  assert.equal(isHeicMime('IMAGE/HEIF'), true)
  assert.equal(isHeicMime('image/avif'), false)
  report.avifBrandWindow = avifBrands.replace(/[^\x20-\x7e]/g, '.')
  scenes.push('avif-excluded-heic-detected')

  // --- HE-11: dimensions come from the primary item, not from a byte scan ---
  const real = readHeicDimensions(heic)
  assert.deepEqual(real, { width: 2048, height: 1536 }, 'the real container must report its own dimensions')

  // A decoy `ispe` (1x1) inside a free box placed before meta must be ignored;
  // the previous string scan returned 1x1 here.
  const decoy = read('decoy-ispe.heic')
  assert(decoy.toString('latin1', 0, Math.min(decoy.length, 4096)).includes('free'))
  assert.deepEqual(readHeicDimensions(decoy), { width: 2048, height: 1536 }, 'a decoy ispe must not shadow the real one')

  // Patched primary ispe: rejected against the pixel budget before any decode.
  const oversized = read('oversized-ispe.heic')
  assert.deepEqual(readHeicDimensions(oversized), { width: 20000, height: 20000 })
  const oversizedStarted = Date.now()
  await assert.rejects(() => decodeHeicToJpeg(oversized), /pixel limit/)
  const oversizedMs = Date.now() - oversizedStarted
  assert(oversizedMs < 2_000, `the pixel bound must reject before decoding (${oversizedMs} ms)`)

  // No usable dimensions: refuse instead of decoding unbounded.
  const missing = read('missing-ispe.heic')
  assert.equal(readHeicDimensions(missing), null)
  await assert.rejects(() => decodeHeicToJpeg(missing), /refusing to decode it without a size bound/)

  // Byte cap.
  const tooBig = Buffer.alloc(MAX_HEIC_BYTES + 1)
  heic.copy(tooBig, 0, 0, Math.min(heic.length, tooBig.length))
  await assert.rejects(() => decodeHeicToJpeg(tooBig), /attachment limit/)

  // Damaged but dimensioned: a readable failure, never silent bytes.
  const truncated = read('truncated.heic')
  let truncatedError = ''
  try { await decodeHeicToJpeg(truncated) } catch (error) { truncatedError = error instanceof Error ? error.message : String(error) }
  assert.match(truncatedError, /HEIC\/HEIF/)
  report.bounds = {
    real, decoy: readHeicDimensions(decoy), oversized: readHeicDimensions(oversized),
    oversizedRejectedInMs: oversizedMs, missingDimensions: null, truncatedError,
  }
  scenes.push('dimensions-resolved-from-primary-item-and-bounded')

  // --- HE-10: the deadline terminates the worker; the loop stays responsive --
  // 1 ms is far below a real decode, so the timer wins and must terminate it.
  const terminatedBefore = heicTranscodeStats.terminated
  const deadlineStarted = Date.now()
  await assert.rejects(() => decodeHeicToJpeg(heic, 0.92, 1), /exceeded 1 ms and was terminated/)
  const deadlineMs = Date.now() - deadlineStarted
  assert(deadlineMs < 5_000, `termination must be prompt (${deadlineMs} ms)`)
  assert(heicTranscodeStats.terminated > terminatedBefore, 'the deadline must terminate the worker, not just reject')

  // Event loop stays responsive while a real transcode runs.
  let beats = 0
  const heartbeat = setInterval(() => { beats++ }, 5)
  const converted = await decodeHeicToJpeg(heic)
  clearInterval(heartbeat)
  assert(beats > 0, 'the event loop must keep ticking during a transcode')
  assert.equal(converted[0], 0xff)
  assert.equal(converted[1], 0xd8)

  // Concurrency stays under the configured limit.
  const beforeMax = heicTranscodeStats.maxConcurrent
  const batch = await Promise.all(Array.from({ length: HEIC_MAX_CONCURRENT_TRANSCODES + 1 }, () => decodeHeicToJpeg(heic)))
  for (const result of batch) assert.equal(result[0], 0xff)
  assert(heicTranscodeStats.maxConcurrent <= HEIC_MAX_CONCURRENT_TRANSCODES,
    `concurrency cap exceeded: ${heicTranscodeStats.maxConcurrent}`)
  report.lifecycle = {
    termination: { message: 'exceeded 1 ms and was terminated', elapsedMs: deadlineMs, terminated: heicTranscodeStats.terminated },
    eventLoopBeatsDuringTranscode: beats,
    concurrency: { limit: HEIC_MAX_CONCURRENT_TRANSCODES, observed: heicTranscodeStats.maxConcurrent, beforeMax },
    stats: { ...heicTranscodeStats },
  }
  scenes.push('deadline-terminates-worker-and-loop-stays-responsive')

  // --- HE-05/HE-06: output, source integrity and processor wiring ----------
  const sharp = (await import('sharp')).default
  const meta = await sharp(converted).metadata()
  assert.equal(meta.format, 'jpeg')
  assert.equal(meta.width, 2048)
  assert.equal(meta.height, 1536)
  const { createHeadlessPlatform } = await import('@phaneris/server-core/runtime')
  const platform = await createHeadlessPlatform({ appVersion: 'verification' })
  assert.deepEqual(await platform.imageProcessor.getMetadata(heic), { width: 2048, height: 1536 })
  const thumbnail = await platform.imageProcessor.process(heic, { resize: { width: 200, height: 200 }, format: 'png' })
  const thumbnailMeta = await sharp(thumbnail).metadata()
  assert.equal(thumbnailMeta.format, 'png')
  assert(thumbnailMeta.width! <= 200 && thumbnailMeta.height! <= 200)
  const passthrough = await ensureDecodableImage(Buffer.from(jpeg))
  assert.equal(sha256(passthrough as Buffer), sha256(jpeg), 'a JPEG must pass through untouched')
  const ensured = await ensureDecodableImage(heic)
  assert.equal((ensured as Buffer)[0], 0xff)
  assert.equal(sha256(readFileSync(join(fixtures, 'photo.heic'))), manifest.samples['photo.heic']!.sha256)
  report.transcode = {
    jpegBytes: converted.length, jpegSha256: sha256(converted), width: meta.width, height: meta.height,
    thumbnail: { bytes: thumbnail.length, sha256: sha256(thumbnail), width: thumbnailMeta.width, height: thumbnailMeta.height },
    sourceUnchanged: true,
  }
  evidence.json('transcode.json', report)
  scenes.push('transcode-output-and-platform-processor')

  // --- HE-08: the bundled Python image tool reads HEIC ---------------------
  const platformKey = `${process.platform}-${process.arch}`
  const packagedUv = join(root, 'apps/electron/resources/bin', platformKey, process.platform === 'win32' ? 'uv.exe' : 'uv')
  const uv = existsSync(packagedUv) ? packagedUv : process.platform === 'win32' ? 'uv.exe' : 'uv'
  const script = join(root, 'apps/electron/resources/scripts/img_tool.py')
  const info = execFileSync(uv, ['run', '--python', '3.12.15', '--quiet', script, 'info', join(fixtures, 'photo.heic')], { encoding: 'utf8', timeout: 900_000 })
  const parsed = JSON.parse(info) as { format: string; width: number; height: number }
  assert.equal(parsed.format, 'HEIF', `pillow-heif must open HEIC (got ${parsed.format})`)
  assert.equal(parsed.width, 2048)
  assert.equal(parsed.height, 1536)
  const jpegOut = join(evidence.directory, 'img-tool-converted.jpg')
  execFileSync(uv, ['run', '--python', '3.12.15', '--quiet', script, 'convert', join(fixtures, 'photo.heic'), '--format', 'jpg', '-o', jpegOut], { timeout: 900_000 })
  const convertedMeta = await sharp(readFileSync(jpegOut)).metadata()
  assert.equal(convertedMeta.format, 'jpeg')
  evidence.json('python-tool.json', {
    info: parsed, uv,
    converted: { path: 'img-tool-converted.jpg', bytes: readFileSync(jpegOut).length, sha256: sha256(readFileSync(jpegOut)) },
  })
  scenes.push('python-img-tool-reads-heic')

  evidence.complete(scenes, [
    'Windows packaged Electron renderer drag/drop/paste path (covered by upgrade-0153-heic-store-workflow)',
    'macOS/Linux execution',
    'live model upload of a transcoded attachment',
  ])
} catch (error) { failure = error }
evidence.json('heic.json', { scenes })
evidence.finish(failure)
console.log(JSON.stringify({ passed: scenes.length, output: evidence.directory }))
